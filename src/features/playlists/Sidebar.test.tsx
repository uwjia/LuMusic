// Behavior tests for the sidebar navigation (api mocked).
import '@testing-library/jest-dom/vitest';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import { act, fireEvent, render, screen } from '@testing-library/react';
import { api } from '@/api';
import { useI18n } from '@/i18n';
import type { Playlist } from '@/types/track';
import { usePlayerStore } from '@/stores/playerStore';
import { usePlaylistStore } from '@/stores/playlistStore';
import { Sidebar } from '@/features/playlists/Sidebar';

vi.mock('@/api', () => ({
  api: {
    playlistList: vi.fn(),
    playlistGetTracks: vi.fn(),
    playlistCreate: vi.fn(),
    playlistRename: vi.fn(),
    playlistDelete: vi.fn(),
    playlistAddTrack: vi.fn(),
    playerLoad: vi.fn(),
  },
}));

const playlists: Playlist[] = [
  { id: 'p1', name: 'Chill', items: ['a', 'b'], createdAt: 1, autoGenerated: false },
  { id: 'p2', name: 'Focus', items: [], createdAt: 2, autoGenerated: false },
];

/** Right-click a playlist row and return the opened custom menu. */
function openMenu(rowLabel: string, menuName = 'Playlist actions') {
  fireEvent.contextMenu(screen.getByText(rowLabel), { clientX: 12, clientY: 34 });
  return screen.getByRole('menu', { name: menuName });
}

beforeEach(() => {
  vi.clearAllMocks();
  vi.mocked(api.playlistList).mockResolvedValue(playlists);
  vi.mocked(api.playlistGetTracks).mockResolvedValue([]);
  vi.mocked(api.playerLoad).mockResolvedValue({
    status: 'playing',
    currentTrack: null,
    queuePosition: 0,
    queueLen: 2,
    positionSecs: 0,
    durationSecs: null,
    volume: 0.8,
    shuffle: false,
    repeat: 'off',
  });
  usePlaylistStore.setState({
    playlists,
    selectedTracks: [],
    selectedId: null,
    error: null,
  });
  usePlayerStore.setState({ state: null, error: null });
});

describe('Sidebar', () => {
  const onNavigate = vi.fn();

  it('lists playlists with item counts', () => {
    render(<Sidebar view={{ kind: 'library' }} onNavigate={onNavigate} />);
    expect(screen.getByText('Chill')).toBeInTheDocument();
    expect(screen.getByText('Focus')).toBeInTheDocument();
    expect(screen.getByText('2')).toBeInTheDocument(); // Chill count
  });

  it('clicking a playlist selects and navigates without starting playback', async () => {
    render(<Sidebar view={{ kind: 'library' }} onNavigate={onNavigate} />);
    fireEvent.click(screen.getByText('Chill'));
    await vi.waitFor(() => expect(api.playlistGetTracks).toHaveBeenCalledWith('p1'));
    expect(onNavigate).toHaveBeenCalledWith({ kind: 'playlist', id: 'p1' });
    // Navigating must never hijack playback - rows are played by double-click.
    expect(api.playerLoad).not.toHaveBeenCalled();
  });

  it('creating a playlist posts the trimmed name', async () => {
    vi.mocked(api.playlistCreate).mockResolvedValue(playlists[0]);
    render(<Sidebar view={{ kind: 'library' }} onNavigate={onNavigate} />);
    fireEvent.click(screen.getByTestId('new-playlist'));
    const input = screen.getByLabelText('New playlist name') as HTMLInputElement;
    fireEvent.change(input, { target: { value: '  Road Trip  ' } });
    fireEvent.submit(input.form!);
    await vi.waitFor(() =>
      expect(api.playlistCreate).toHaveBeenCalledWith('Road Trip'),
    );
  });

  it('shows auto playlists localized while manual ones stay verbatim', () => {
    // Backend canonical names ("All Tracks" / "Default", ids auto:all /
    // auto:root) are translated at render time; folder autos and manual
    // playlists are user data and keep their stored names.
    const mixed: Playlist[] = [
      { id: 'auto:root', name: 'Default', items: [], createdAt: 1, autoGenerated: true },
      { id: 'auto:dir:Rock', name: 'Rock', items: [], createdAt: 2, autoGenerated: true },
      { id: 'p1', name: 'Chill', items: [], createdAt: 3, autoGenerated: false },
    ];
    usePlaylistStore.setState({ playlists: mixed, selectedTracks: [], selectedId: null, error: null });
    render(<Sidebar view={{ kind: 'library' }} onNavigate={vi.fn()} />);
    expect(screen.getByText('Default')).toBeInTheDocument();
    expect(screen.getByText('Rock')).toBeInTheDocument();
    expect(screen.getByText('Chill')).toBeInTheDocument();
  });

  it('renders the fixed auto playlists in Chinese after a locale switch', () => {
    const auto: Playlist[] = [
      { id: 'auto:all', name: 'All Tracks', items: ['a'], createdAt: 1, autoGenerated: true },
      { id: 'auto:root', name: 'Default', items: ['a'], createdAt: 2, autoGenerated: true },
    ];
    usePlaylistStore.setState({ playlists: auto, selectedTracks: [], selectedId: null, error: null });
    act(() => {
      useI18n.getState().setLocale('zh-CN');
    });
    try {
      render(<Sidebar view={{ kind: 'library' }} onNavigate={vi.fn()} />);
      expect(screen.getByText('全部曲目')).toBeInTheDocument();
      expect(screen.getByText('默认歌单')).toBeInTheDocument();
      // The stored names are only a display concern - they must not leak
      // into the rendered list.
      expect(screen.queryByText('All Tracks')).not.toBeInTheDocument();
      expect(screen.queryByText('Default')).not.toBeInTheDocument();
    } finally {
      act(() => {
        useI18n.getState().setLocale('en');
      });
    }
  });

  it('keeps duplicate-name errors visible for correction', async () => {
    vi.mocked(api.playlistCreate).mockRejectedValue(
      new Error("a playlist named 'Chill' already exists"),
    );
    render(<Sidebar view={{ kind: 'library' }} onNavigate={onNavigate} />);
    fireEvent.click(screen.getByTestId('new-playlist'));
    const input = screen.getByLabelText('New playlist name') as HTMLInputElement;
    fireEvent.change(input, { target: { value: 'Chill' } });
    fireEvent.submit(input.form!);
    await vi.waitFor(() =>
      expect(screen.getByRole('alert')).toHaveTextContent('already exists'),
    );
  });
});

describe('Sidebar playlist context menu', () => {
  it('right-clicking a row opens a menu with rename, duplicate and delete', () => {
    render(<Sidebar view={{ kind: 'library' }} onNavigate={vi.fn()} />);
    const menu = openMenu('Chill');
    expect(menu).toBeInTheDocument();
    expect(screen.getByRole('menuitem', { name: 'Rename' })).toBeInTheDocument();
    expect(screen.getByRole('menuitem', { name: 'Duplicate' })).toBeInTheDocument();
    expect(screen.getByRole('menuitem', { name: 'Delete playlist' })).toBeInTheDocument();
    // Escape dismisses it without touching the api.
    fireEvent.keyDown(document, { key: 'Escape' });
    expect(screen.queryByRole('menu')).not.toBeInTheDocument();
    expect(api.playlistRename).not.toHaveBeenCalled();
    expect(api.playlistDelete).not.toHaveBeenCalled();
  });

  it('dismisses the menu on an outside pointer press', () => {
    render(<Sidebar view={{ kind: 'library' }} onNavigate={vi.fn()} />);
    openMenu('Focus');
    fireEvent.pointerDown(document.body);
    expect(screen.queryByRole('menu')).not.toBeInTheDocument();
  });

  it('duplicates via create + per-track addTrack', async () => {
    vi.mocked(api.playlistCreate).mockResolvedValue({
      id: 'p3',
      name: 'Chill (copy)',
      items: [],
      createdAt: 3,
      autoGenerated: false,
    });
    vi.mocked(api.playlistAddTrack).mockResolvedValue(true);
    render(<Sidebar view={{ kind: 'library' }} onNavigate={vi.fn()} />);
    openMenu('Chill');
    fireEvent.click(screen.getByRole('menuitem', { name: 'Duplicate' }));
    await vi.waitFor(() => expect(api.playlistCreate).toHaveBeenCalledWith('Chill (copy)'));
    await vi.waitFor(() => expect(api.playlistAddTrack).toHaveBeenCalledTimes(2));
    expect(api.playlistAddTrack).toHaveBeenNthCalledWith(1, 'p3', 'a');
    expect(api.playlistAddTrack).toHaveBeenNthCalledWith(2, 'p3', 'b');
  });

  it('deletes the right-clicked playlist', async () => {
    vi.mocked(api.playlistDelete).mockResolvedValue(undefined);
    render(<Sidebar view={{ kind: 'library' }} onNavigate={vi.fn()} />);
    openMenu('Focus');
    fireEvent.click(screen.getByRole('menuitem', { name: 'Delete playlist' }));
    await vi.waitFor(() => expect(api.playlistDelete).toHaveBeenCalledWith('p2'));
  });

  it('renames via the inline editor with a trimmed name', async () => {
    vi.mocked(api.playlistRename).mockResolvedValue(undefined);
    render(<Sidebar view={{ kind: 'library' }} onNavigate={vi.fn()} />);
    openMenu('Chill');
    fireEvent.click(screen.getByRole('menuitem', { name: 'Rename' }));
    const input = screen.getByLabelText('Playlist name') as HTMLInputElement;
    expect(input.value).toBe('Chill');
    fireEvent.change(input, { target: { value: '  Road Trip  ' } });
    fireEvent.submit(input.form!);
    await vi.waitFor(() => expect(api.playlistRename).toHaveBeenCalledWith('p1', 'Road Trip'));
    await vi.waitFor(() =>
      expect(screen.queryByLabelText('Playlist name')).not.toBeInTheDocument(),
    );
  });

  it('closing the inline editor without changes skips the api', () => {
    render(<Sidebar view={{ kind: 'library' }} onNavigate={vi.fn()} />);
    openMenu('Chill');
    fireEvent.click(screen.getByRole('menuitem', { name: 'Rename' }));
    fireEvent.keyDown(screen.getByLabelText('Playlist name'), { key: 'Escape' });
    expect(api.playlistRename).not.toHaveBeenCalled();
    expect(screen.queryByLabelText('Playlist name')).not.toBeInTheDocument();
  });

  it('seeds the inline editor with the canonical name of auto playlists', () => {
    // The visible label is localized ("默认歌单") but the stored name
    // ("Default") is the rename payload seed - writing the translated
    // name back would orphan the playlist on the next rescan.
    const auto: Playlist[] = [
      { id: 'auto:root', name: 'Default', items: ['a'], createdAt: 1, autoGenerated: true },
    ];
    usePlaylistStore.setState({ playlists: auto, selectedTracks: [], selectedId: null, error: null });
    act(() => {
      useI18n.getState().setLocale('zh-CN');
    });
    try {
      render(<Sidebar view={{ kind: 'library' }} onNavigate={vi.fn()} />);
      openMenu('默认歌单', '歌单操作');
      fireEvent.click(screen.getByRole('menuitem', { name: '重命名' }));
      expect((screen.getByLabelText('歌单名称') as HTMLInputElement).value).toBe('Default');
    } finally {
      act(() => {
        useI18n.getState().setLocale('en');
      });
    }
  });

  it('keeps the editor open and shows the error when rename fails', async () => {
    vi.mocked(api.playlistRename).mockRejectedValue(
      new Error("a playlist named 'Focus' already exists"),
    );
    render(<Sidebar view={{ kind: 'library' }} onNavigate={vi.fn()} />);
    openMenu('Chill');
    fireEvent.click(screen.getByRole('menuitem', { name: 'Rename' }));
    const input = screen.getByLabelText('Playlist name') as HTMLInputElement;
    fireEvent.change(input, { target: { value: 'Focus' } });
    fireEvent.submit(input.form!);
    await vi.waitFor(() => expect(screen.getByRole('alert')).toHaveTextContent('already exists'));
    expect(screen.getByLabelText('Playlist name')).toBeInTheDocument();
  });
});
