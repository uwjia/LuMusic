// Behavior tests for the playlist page header actions (api mocked).
import '@testing-library/jest-dom/vitest';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import { act } from '@testing-library/react';
import { api } from '@/api';
import { useI18n } from '@/i18n';
import type { Playlist, Track } from '@/types/track';
import { usePlayerStore } from '@/stores/playerStore';
import { usePlaylistStore } from '@/stores/playlistStore';
import { PlaylistPage } from '@/features/playlists/PlaylistPage';

vi.mock('@/api', () => ({
  api: {
    playlistList: vi.fn(),
    playlistGetTracks: vi.fn(),
    playlistCreate: vi.fn(),
    playlistRename: vi.fn(),
    playlistDelete: vi.fn(),
    playlistAddTrack: vi.fn(),
    playlistRemoveTrack: vi.fn(),
  },
}));

const playlist: Playlist = {
  id: 'p1',
  name: 'Road Trip',
  items: ['a', 'b'],
  createdAt: 1,
  autoGenerated: false,
};

const track = (id: string): Track => ({
  id,
  title: id,
  artist: null,
  album: null,
  albumArtist: null,
  trackNo: null,
  discNo: null,
  year: null,
  genre: null,
  durationSecs: 60,
  filePath: `C:/m/${id}.mp3`,
  sizeBytes: 1,
});

const tracks = [track('a'), track('b')];

beforeEach(() => {
  vi.clearAllMocks();
  vi.mocked(api.playlistList).mockResolvedValue([playlist]);
  usePlaylistStore.setState({
    playlists: [playlist],
    selectedTracks: tracks,
    selectedId: 'p1',
    error: null,
  });
  usePlayerStore.setState({ state: null, error: null });
});

describe('PlaylistPage', () => {
  it('titles the fixed auto playlists with the localized display name', () => {
    const autoPlaylist: Playlist = {
      id: 'auto:root',
      name: 'Default',
      items: ['a'],
      createdAt: 1,
      autoGenerated: true,
    };
    usePlaylistStore.setState({
      playlists: [autoPlaylist],
      selectedTracks: [tracks[0]],
      selectedId: 'auto:root',
      error: null,
    });
    act(() => {
      useI18n.getState().setLocale('zh-CN');
    });
    try {
      render(<PlaylistPage playlistId="auto:root" />);
      expect(screen.getByRole('heading', { name: '默认歌单' })).toBeInTheDocument();
    } finally {
      act(() => {
        useI18n.getState().setLocale('en');
      });
    }
  });

  it('duplicates via create + per-track addTrack', async () => {
    vi.mocked(api.playlistCreate).mockResolvedValue({
      id: 'p2',
      name: 'Road Trip (copy)',
      items: [],
      createdAt: 2,
      autoGenerated: false,
    });
    vi.mocked(api.playlistAddTrack).mockResolvedValue(true);
    render(<PlaylistPage playlistId="p1" />);
    fireEvent.click(screen.getByText('Duplicate'));
    await waitFor(() => expect(api.playlistCreate).toHaveBeenCalledWith('Road Trip (copy)'));
    await waitFor(() => expect(api.playlistAddTrack).toHaveBeenCalledTimes(2));
    expect(api.playlistAddTrack).toHaveBeenNthCalledWith(1, 'p2', 'a');
    expect(api.playlistAddTrack).toHaveBeenNthCalledWith(2, 'p2', 'b');
  });

  it('renames via the inline editor with a trimmed name', async () => {
    vi.mocked(api.playlistRename).mockResolvedValue(undefined);
    render(<PlaylistPage playlistId="p1" />);
    fireEvent.click(screen.getByText('Rename'));
    const input = screen.getByLabelText('Playlist name') as HTMLInputElement;
    expect(input.value).toBe('Road Trip');
    fireEvent.change(input, { target: { value: '  Focus  ' } });
    fireEvent.submit(input.form!);
    await waitFor(() => expect(api.playlistRename).toHaveBeenCalledWith('p1', 'Focus'));
    await waitFor(() => expect(screen.queryByLabelText('Playlist name')).not.toBeInTheDocument());
  });

  it('closing the editor without changes skips the api', () => {
    render(<PlaylistPage playlistId="p1" />);
    fireEvent.click(screen.getByText('Rename'));
    fireEvent.click(screen.getByText('Cancel'));
    expect(api.playlistRename).not.toHaveBeenCalled();
    expect(screen.queryByLabelText('Playlist name')).not.toBeInTheDocument();
  });

  it('keeps the editor open and shows the error when rename fails', async () => {
    vi.mocked(api.playlistRename).mockRejectedValue(
      new Error("a playlist named 'Focus' already exists"),
    );
    render(<PlaylistPage playlistId="p1" />);
    fireEvent.click(screen.getByText('Rename'));
    const input = screen.getByLabelText('Playlist name') as HTMLInputElement;
    fireEvent.change(input, { target: { value: 'Focus' } });
    fireEvent.submit(input.form!);
    await waitFor(() => expect(screen.getByRole('alert')).toHaveTextContent('already exists'));
    expect(screen.getByLabelText('Playlist name')).toBeInTheDocument();
  });
});
