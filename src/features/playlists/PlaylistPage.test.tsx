// Behavior tests for the playlist page (api mocked).
// Rename / duplicate / delete moved to the sidebar context menu — these
// tests pin that the page stays a viewer/editor of the playlist's tracks.
import '@testing-library/jest-dom/vitest';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import { render, screen } from '@testing-library/react';
import { act } from '@testing-library/react';
import { api } from '@/api';
import { useI18n } from '@/i18n';
import type { Playlist, Track } from '@/types/track';
import { usePlayerStore } from '@/stores/playerStore';
import { usePlaylistStore } from '@/stores/playlistStore';
import { PlaylistPage } from '@/features/playlists/PlaylistPage';

vi.mock('@/api', () => ({
  api: {
    playlistList: vi.fn(),
    playlistGetTracks: vi.fn(),
    playlistRemoveTrack: vi.fn(),
    playlistMoveTrack: vi.fn(),
    playerLoad: vi.fn(),
  },
}));

const playlist: Playlist = {
  id: 'p1',
  name: 'Road Trip',
  items: ['a', 'b'],
  createdAt: 1,
  autoGenerated: false,
};

const track = (id: string): Track => ({
  id,
  title: id,
  artist: null,
  album: null,
  albumArtist: null,
  trackNo: null,
  discNo: null,
  year: null,
  genre: null,
  durationSecs: 60,
  filePath: `C:/m/${id}.mp3`,
  sizeBytes: 1,
});

const tracks = [track('a'), track('b')];

beforeEach(() => {
  vi.clearAllMocks();
  vi.mocked(api.playlistList).mockResolvedValue([playlist]);
  usePlaylistStore.setState({
    playlists: [playlist],
    selectedTracks: tracks,
    selectedId: 'p1',
    error: null,
  });
  usePlayerStore.setState({ state: null, error: null });
});

describe('PlaylistPage', () => {
  it('shows the name and track count only - playlist actions live in the sidebar', () => {
    render(<PlaylistPage playlistId="p1" />);
    expect(screen.getByRole('heading', { name: 'Road Trip' })).toBeInTheDocument();
    expect(screen.getByText('2 tracks')).toBeInTheDocument();
    // The header no longer hosts rename/duplicate/delete.
    expect(screen.queryByRole('button', { name: 'Rename' })).not.toBeInTheDocument();
    expect(screen.queryByRole('button', { name: 'Duplicate' })).not.toBeInTheDocument();
    expect(screen.queryByRole('button', { name: 'Delete playlist' })).not.toBeInTheDocument();
  });

  it('titles the fixed auto playlists with the localized display name', () => {
    const autoPlaylist: Playlist = {
      id: 'auto:root',
      name: 'Default',
      items: ['a'],
      createdAt: 1,
      autoGenerated: true,
    };
    usePlaylistStore.setState({
      playlists: [autoPlaylist],
      selectedTracks: [tracks[0]],
      selectedId: 'auto:root',
      error: null,
    });
    act(() => {
      useI18n.getState().setLocale('zh-CN');
    });
    try {
      render(<PlaylistPage playlistId="auto:root" />);
      expect(screen.getByRole('heading', { name: '默认歌单' })).toBeInTheDocument();
    } finally {
      act(() => {
        useI18n.getState().setLocale('en');
      });
    }
  });

  it('reports a missing playlist', () => {
    render(<PlaylistPage playlistId="gone" />);
    expect(screen.getByText('Playlist not found')).toBeInTheDocument();
  });
});
