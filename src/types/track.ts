// DTO types mirroring the Rust backend (serde camelCase).
// Keep in sync with src-tauri/src/domain and src-tauri/src/app/dto.rs.

export type TrackId = string;

export interface Track {
  id: TrackId;
  title: string;
  artist: string | null;
  album: string | null;
  albumArtist: string | null;
  trackNo: number | null;
  discNo: number | null;
  year: number | null;
  genre: string | null;
  durationSecs: number | null;
  filePath: string;
  sizeBytes: number;
}

export type SortField = 'title' | 'artist' | 'album';

export interface TrackQuery {
  search: string | null;
  sort: SortField;
  descending: boolean;
}

export type RepeatMode = 'off' | 'all' | 'one';

export type PlaybackStatus = 'stopped' | 'playing' | 'paused';

export interface PlayerState {
  status: PlaybackStatus;
  currentTrack: Track | null;
  queuePosition: number | null;
  queueLen: number;
  positionSecs: number;
  durationSecs: number | null;
  volume: number;
  shuffle: boolean;
  repeat: RepeatMode;
}

export interface Playlist {
  id: string;
  name: string;
  items: TrackId[];
  createdAt: number;
  /** True for playlists generated from the folder structure on each scan. */
  autoGenerated: boolean;
}

export interface ScanSummary {
  root: string;
  filesSeen: number;
  added: number;
  updated: number;
  removed: number;
  skipped: number;
  warnings: string[];
}

export interface ScanProgress {
  scanned: number;
  total: number;
}

export interface Settings {
  volume: number;
  lastFolder: string | null;
  /** Keep running in the tray (music keeps playing) when the window closes. */
  closeToTray: boolean;
  /** Equalizer configuration (mirrors `EqSettings` in domain/equalizer.rs). */
  eq: EqSettings;
}

export interface EqSettings {
  enabled: boolean;
  /** Global gain before the band filters, in dB. */
  preampDb: number;
  /** Per-band gains in dB; always `EQ_BAND_COUNT` entries. */
  gainsDb: number[];
}

/** Localized labels for the native tray menu, pushed from the i18n layer
 * (mirrors `TrayLabels` in src-tauri/src/app/tray.rs). */
export interface TrayLabels {
  play: string;
  pause: string;
  previous: string;
  next: string;
  show: string;
  quit: string;
  nothingPlaying: string;
}

export interface ProgressPayload {
  positionSecs: number;
  durationSecs: number | null;
}

/** One synced lyric line (parsed from a sibling `.lrc` file by the backend). */
export interface LyricLine {
  timeMs: number;
  /** Empty string marks an interlude (rendered as a spacer). */
  text: string;
}

/** Lyrics associated with a track via `lyricsGet`; null = no `.lrc` file. */
export interface Lyrics {
  /** Path of the matched `.lrc` file (proves the association to the user). */
  sourcePath: string | null;
  lines: LyricLine[];
}

// Event names (mirror src-tauri/src/events.rs).
export const PLAYER_STATE_EVENT = 'player://state';
export const PLAYER_PROGRESS_EVENT = 'player://progress';
export const LIBRARY_UPDATED_EVENT = 'library://updated';
export const LIBRARY_SCAN_PROGRESS_EVENT = 'library://scan-progress';
