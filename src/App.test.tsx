// App shell wiring tests (api mocked at the seam; stores seeded via setState).
// Pins the interaction between sidebar navigation and the lyrics page.
import { beforeEach, describe, expect, it, vi } from 'vitest';
import { act, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { api } from '@/api';
import type { PlayerState, Playlist, Track } from '@/types/track';
import App from '@/App';
import { useLyricsStore } from '@/stores/lyricsStore';
import { usePlayerStore } from '@/stores/playerStore';
import { usePlaylistStore } from '@/stores/playlistStore';
import { SILENT_FRAME, useSpectrumStore } from '@/stores/spectrumStore';

vi.mock('@/api', () => {
  const unsubscribe = () => () => {};
  return {
    api: {
      appInfo: vi.fn(async () => ({ name: 'lumusic', version: '0.0.0' })),
      playerState: vi.fn(),
      getTracks: vi.fn(async () => [] as Track[]),
      playlistList: vi.fn(async () => [] as Playlist[]),
      playlistGetTracks: vi.fn(async () => [] as Track[]),
      lyricsGet: vi.fn(),
      traySetLabels: vi.fn(async () => undefined),
      onSpectrum: vi.fn(unsubscribe),
      onPlayerState: vi.fn(unsubscribe),
      onProgress: vi.fn(unsubscribe),
      onScanProgress: vi.fn(unsubscribe),
      onLibraryUpdated: vi.fn(unsubscribe),
    },
  };
});

const track: Track = {
  id: 't1',
  title: 'I Will Do',
  artist: 'Pierre',
  album: null,
  albumArtist: null,
  trackNo: null,
  discNo: null,
  year: null,
  genre: null,
  durationSecs: 205,
  filePath: 'C:/Data/Music/吸血鬼日记/will_do.mp3',
  sizeBytes: 1,
};

const playing: PlayerState = {
  status: 'playing',
  currentTrack: track,
  queuePosition: 0,
  queueLen: 1,
  positionSecs: 1,
  durationSecs: 205,
  volume: 0.5,
  shuffle: false,
  repeat: 'off',
};

const playlists: Playlist[] = [
  { id: 'p1', name: 'Chill', items: ['t1'], createdAt: 1, autoGenerated: false },
];

beforeEach(() => {
  vi.clearAllMocks();
  vi.mocked(api.playerState).mockResolvedValue(playing);
  vi.mocked(api.playlistList).mockResolvedValue(playlists);
  vi.mocked(api.playlistGetTracks).mockResolvedValue([]);
  vi.mocked(api.lyricsGet).mockResolvedValue({
    sourcePath: 'C:/Data/Music/吸血鬼日记/will_do.lrc',
    lines: [{ timeMs: 760, text: 'I will do do do do do' }],
  });
  usePlayerStore.setState({ state: playing, error: null });
  usePlaylistStore.setState({ playlists, selectedTracks: [], selectedId: null, error: null });
  useSpectrumStore.setState({ open: false, frame: [...SILENT_FRAME] });
  useLyricsStore.setState({
    open: true,
    trackId: null,
    lines: [],
    sourcePath: null,
    status: 'idle',
    error: null,
  });
});

describe('App spectrum overlay', () => {
  it('mounts the panel inside the content area, not the player bar', () => {
    useSpectrumStore.setState({ open: true });
    const { container } = render(<App />);
    // Anchored to .content so it centers on the page's visual center
    // (sidebar excluded); the player bar must not own the overlay.
    expect(container.querySelector('.content .spectrum-panel')).toBeInTheDocument();
    expect(container.querySelector('.player-bar .spectrum-panel')).not.toBeInTheDocument();

    // The toggle's contract (store flag) drives mounting both ways.
    act(() => {
      useSpectrumStore.getState().setOpen(false);
    });
    expect(container.querySelector('.content .spectrum-panel')).not.toBeInTheDocument();
  });
});

describe('App sidebar navigation vs lyrics page', () => {
  it('clicking a playlist in the sidebar hides the lyrics page', async () => {
    render(<App />);
    // Lyrics page is up (store flag) and loads its lines.
    expect(await screen.findByTestId('lyrics-page')).toBeInTheDocument();
    expect(await screen.findByText('I will do do do do do')).toBeInTheDocument();

    fireEvent.click(screen.getByText('Chill'));

    // The playlist view replaces the lyrics page and the flag is cleared,
    // so the player-bar toggle returns to its "show" state.
    await waitFor(() => expect(screen.getByTestId('playlist-page')).toBeInTheDocument());
    expect(screen.queryByTestId('lyrics-page')).not.toBeInTheDocument();
    expect(useLyricsStore.getState().open).toBe(false);
  });

  it('clicking the library nav also dismisses the lyrics page', async () => {
    render(<App />);
    expect(await screen.findByTestId('lyrics-page')).toBeInTheDocument();

    fireEvent.click(screen.getByRole('button', { name: /library/i }));

    await waitFor(() =>
      expect(screen.queryByTestId('lyrics-page')).not.toBeInTheDocument(),
    );
    expect(useLyricsStore.getState().open).toBe(false);
  });
});
