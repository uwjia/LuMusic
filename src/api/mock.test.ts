// Behavior tests for the in-memory mock api (kept in lockstep with the
// backend's auto-playlist rules).
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { mockApi } from '@/api/mock';

beforeEach(async () => {
  vi.useFakeTimers();
  // Drive the mock into the post-scan state each test relies on.
  await mockApi.scanLibrary('C:/mock-music');
});

afterEach(() => {
  vi.useRealTimers();
});

describe('mock spectrum seam', () => {
  // Runs first: the mock singleton's ticker interval is created inside
  // *this* test's fake-timer environment (later beforeEach calls replace
  // the fake clock, which orphans intervals registered earlier).
  it('emits 24-bar frames while playing and stops when paused', async () => {
    const frames: number[][] = [];
    const unsubscribe = mockApi.onSpectrum((frame) => frames.push(frame));
    const tracks = await mockApi.playlistGetTracks('auto:root');
    await mockApi.playerLoad(tracks.map((t) => t.id), 0);
    await vi.advanceTimersByTimeAsync(1_000);
    expect(frames.length).toBeGreaterThanOrEqual(3);
    for (const frame of frames) {
      expect(frame).toHaveLength(24);
      expect(frame.every((bar) => bar >= 0 && bar <= 1)).toBe(true);
    }

    // Paused tracks emit nothing new.
    const countWhenPaused = frames.length;
    await mockApi.playerPause();
    await vi.advanceTimersByTimeAsync(1_000);
    expect(frames.length).toBe(countWhenPaused);
    unsubscribe();
  });
});

describe('mock auto playlists', () => {
  it('creates All Tracks, Default and per-folder playlists on scan', async () => {
    const playlists = await mockApi.playlistList();
    const names = playlists.map((p) => [p.name, p.autoGenerated, p.items.length] as const);
    // Sorted by id (matching the backend's BTreeMap): auto:all < auto:dir:* < auto:root.
    expect(names).toEqual([
      ['All Tracks', true, 5],
      ['Nova Fields', true, 1],
      ['The Ember Set', true, 2],
      ['Default', true, 2],
    ]);
  });

  it('updates auto playlists on rescan and keeps manual ones', async () => {
    await mockApi.playlistCreate('My Mix');
    // Rescan is idempotent: no duplicates appear.
    await mockApi.scanLibrary('C:/mock-music');
    const playlists = await mockApi.playlistList();
    const allTracks = playlists.find((p) => p.name === 'All Tracks');
    expect(allTracks?.items).toHaveLength(5);
    expect(playlists.filter((p) => p.name === 'All Tracks')).toHaveLength(1);
    expect(playlists.find((p) => p.name === 'My Mix')?.autoGenerated).toBe(false);
  });

  it('adopts a manual playlist with the same name instead of duplicating', async () => {
    // Simulate the legacy situation: delete the auto playlist, create a
    // manual one with the same name, then rescan.
    await mockApi.playlistDelete('auto:dir:The Ember Set');
    await mockApi.playlistCreate('The Ember Set');

    await mockApi.scanLibrary('C:/mock-music');
    let lists = await mockApi.playlistList();
    let matches = lists.filter((p) => p.name === 'The Ember Set');
    expect(matches).toHaveLength(1);
    expect(matches[0].autoGenerated).toBe(true);
    expect(matches[0].items).toHaveLength(2);

    // Repeated scans stay idempotent.
    await mockApi.scanLibrary('C:/mock-music');
    lists = await mockApi.playlistList();
    matches = lists.filter((p) => p.name === 'The Ember Set');
    expect(matches).toHaveLength(1);
    expect(matches[0].items).toHaveLength(2);
  });

  it('playlist items resolve to playable tracks', async () => {
    // Look up by name: after the adoption test the folder playlist may live
    // under a previously-manual id.
    const lists = await mockApi.playlistList();
    const folder = lists.find((p) => p.name === 'The Ember Set');
    expect(folder).toBeTruthy();
    const tracks = await mockApi.playlistGetTracks(folder!.id);
    expect(tracks.map((t) => t.title)).toEqual(['Crimson Sky', 'Drift']);
    // Loading those ids yields a playable queue starting at the first track.
    const state = await mockApi.playerLoad(tracks.map((t) => t.id), 0);
    expect(state.status).toBe('playing');
    expect(state.currentTrack?.id).toBe(tracks[0].id);
    expect(state.queueLen).toBe(2);
  });

  it('repeat modes cycle the queue like the backend', async () => {
    const tracks = await mockApi.playlistGetTracks('auto:root');
    await mockApi.playerLoad(tracks.map((t) => t.id), 1); // last track
    await mockApi.playerSetMode(false, 'all');
    // Manual next with repeat-all wraps to the first track.
    const state = await mockApi.playerNext();
    expect(state.queuePosition).toBe(0);
    // Repeat one restarts the current track when it ends.
    await mockApi.playerSetMode(false, 'one');
    await vi.advanceTimersByTimeAsync(1_000_000);
    const after = await mockApi.playerState();
    expect(after.status).toBe('playing');
    expect(after.positionSecs).toBeLessThan(after.durationSecs ?? Infinity);
  });

  // Mirrors the backend: every progress tick names the track it belongs to,
  // and next/previous restart the position at 0 — together the UI can drop
  // pre-switch ticks instead of rewinding the seek bar.
  it('next restarts at 0 and tags progress ticks with the playing track', async () => {
    // Stop first: it re-arms the singleton's ticker inside this test's own
    // fake clock (see playerStop), so the interval actually fires here.
    await mockApi.playerStop();
    const tracks = await mockApi.playlistGetTracks('auto:root');
    await mockApi.playerLoad(tracks.map((t) => t.id), 0);
    await vi.advanceTimersByTimeAsync(1_000);
    expect((await mockApi.playerState()).positionSecs).toBeGreaterThan(0);

    const ticks: { trackId: string | null; positionSecs: number }[] = [];
    const unsubscribe = mockApi.onProgress((p) =>
      ticks.push({ trackId: p.trackId, positionSecs: p.positionSecs }),
    );
    const after = await mockApi.playerNext();
    expect(after.currentTrack?.id).toBe(tracks[1].id);
    expect(after.positionSecs).toBe(0); // next restarts from the beginning

    await vi.advanceTimersByTimeAsync(1_000);
    expect(ticks.length).toBeGreaterThan(0);
    expect(ticks.every((t) => t.trackId === tracks[1].id)).toBe(true);
    expect(ticks[0].positionSecs).toBe(0.25);
    unsubscribe();
  });
});

describe('mock settings + tray seam', () => {
  it('settingsGet exposes closeToTray and settingsSet only changes provided fields', async () => {
    expect((await mockApi.settingsGet()).closeToTray).toBe(true);
    const updated = await mockApi.settingsSet({ closeToTray: false });
    expect(updated.closeToTray).toBe(false);
    expect((await mockApi.settingsGet()).closeToTray).toBe(false);
    // Calling without fields is a no-op (mirrors player_set_mode).
    await mockApi.settingsSet({});
    expect((await mockApi.settingsGet()).closeToTray).toBe(false);
  });

  it('eq round-trips through settingsSet with backend-style sanitization', async () => {
    // mockApi is a shared singleton: capture the sibling field first so the
    // assertion holds regardless of test order.
    const before = await mockApi.settingsGet();
    const updated = await mockApi.settingsSet({
      eq: { enabled: true, preampDb: 99, gainsDb: [99, Number.NaN, -99, 5] },
    });
    expect(updated.eq.enabled).toBe(true);
    // Clamped to ±12, NaN collapsed, padded to ten bands.
    expect(updated.eq.preampDb).toBe(12);
    expect(updated.eq.gainsDb).toEqual([12, 0, -12, 5, 0, 0, 0, 0, 0, 0]);
    expect((await mockApi.settingsGet()).eq).toEqual(updated.eq);
    // Other fields are untouched by an eq-only patch.
    expect((await mockApi.settingsGet()).closeToTray).toBe(before.closeToTray);
  });

  it('records the last pushed tray labels', async () => {
    expect(mockApi.lastTrayLabels).toBeNull();
    await mockApi.traySetLabels({
      play: 'Play',
      pause: 'Pause',
      previous: 'Previous track',
      next: 'Next track',
      show: 'Show LuMusic',
      quit: 'Quit',
      nothingPlaying: 'Nothing playing',
    });
    expect(mockApi.lastTrayLabels?.quit).toBe('Quit');
  });
});

describe('mock lyrics seam', () => {
  it('serves parsed lyrics for the track with a sibling lrc, null otherwise', async () => {
    const lyrics = await mockApi.lyricsGet('t1');
    expect(lyrics?.sourcePath).toBe('C:/mock-music/Alpha Waves.lrc');
    expect(lyrics?.lines[0]).toEqual({ timeMs: 0, text: 'Nova Fields - Alpha Waves' });
    // Empty-text interludes survive, mirroring the backend parser.
    expect(lyrics?.lines.some((l) => l.text === '')).toBe(true);
    // Every other track has no .lrc sibling.
    expect(await mockApi.lyricsGet('t2')).toBeNull();
  });
});
